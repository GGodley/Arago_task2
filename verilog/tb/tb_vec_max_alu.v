// Self-checking testbench for vec_max_alu.
// Verilog-2001 version of tb/tb_vec_max_alu.sv (compiles with iverilog -g2001).
//
// SV -> Verilog translation notes:
//   * The SV testbench was already written almost entirely in Verilog style. The
//     only SV-only construct was $urandom (unsigned random). Verilog-2001 has only
//     $random, which returns a SIGNED 32-bit value, so "$random % 4" can be
//     negative. Every "$urandom % N" became "{$random} % N": the concatenation
//     braces make the value unsigned, a standard Verilog idiom.
//   * The random stream differs from the SV run, so the random-phase stimulus is
//     different, but the golden vectors and every check are the same.
//
// Two independent references:
//   1. Golden vectors (tb/vectors.hex) generated by scripts/gen_vectors.py from a plain
//      Python max (IEEE 754-2019 'maximum' for BF16).
//   2. A behavioural SystemVerilog model (ref_model below) that converts BF16 to real
//      numbers. It is also cross-checked against every golden vector.
//
// Checks: result value, latency (PIPE+2 edges), no lost/extra outputs, no X on result
// when out_valid, back-to-back throughput, random valid gaps, mode changing every cycle,
// mid-stream reset. Prints coverage of winning lane per mode and BF16 value classes.
//
// Plusargs: +VECTORS=<file>  +NRAND=<n>  +VCD (dump first 2000 cycles to build/wave.vcd)
`timescale 1ns/1ps

module tb_vec_max_alu;
    parameter integer PIPE = 1;
    localparam integer LAT  = PIPE + 2;
    localparam integer MAXV = 262144;
    localparam integer QSZ  = 256;

    // ---------------- DUT ----------------
    reg         clk = 1'b0;
    reg         rst_n = 1'b0;
    reg         in_valid = 1'b0;
    reg  [1:0]  mode = 2'b00;
    reg  [63:0] in_vec = 64'd0;
    wire        out_valid;
    wire [15:0] result;

    vec_max_alu #(.PIPE(PIPE)) dut (
        .clk(clk), .rst_n(rst_n), .in_valid(in_valid), .mode(mode),
        .in_vec(in_vec), .out_valid(out_valid), .result(result)
    );

    always #5 clk = ~clk;

    // ---------------- state ----------------
    reg [83:0]  mem [0:MAXV-1];
    reg [15:0]  exp_q  [0:QSZ-1];
    reg [1:0]   mode_q [0:QSZ-1];
    reg [63:0]  in_q   [0:QSZ-1];
    integer     t_q    [0:QSZ-1];
    integer     wr = 0, rd = 0;
    integer     cycle = 0;
    integer     errors = 0, checked = 0, ref_mismatch = 0, nvec = 0, nrand = 100000;
    reg [15:0]  cur_exp = 16'd0;
    reg [8*256-1:0] vecfile;

    integer     cov_lane [0:23];   // mode*8 + lane   (mode 0..2)
    integer     cov_nan_out = 0;
    integer     cov_bf [0:9];      // class*2 + sign : 0 zero, 1 subnormal, 2 normal, 3 inf, 4 nan
    integer     cov_mode [0:3];
    integer     i, k, lane_w, m_lane;
    reg [15:0]  r_ref, m_ref;

    // ---------------- reference model (behavioural, independent of the DUT algorithm) ----------------
    function automatic real bf2real(input [15:0] x);
        integer e, m;
        real    r;
        begin
            e = x[14:7];
            m = x[6:0];
            if (e == 0)        r = m * (2.0 ** (-133));          // subnormal: 2^-126 * m/128
            else if (e == 255) r = 1.0e300;                      // infinity (NaN handled by caller)
            else               r = (128 + m) * (2.0 ** (e - 134)); // normal: 2^(e-127) * (1 + m/128)
            bf2real = x[15] ? -r : r;
        end
    endfunction

    task automatic ref_model(input [1:0] md, input [63:0] v, output [15:0] r, output integer lane);
        integer j;
        reg signed [7:0]  b8, best8;
        reg signed [15:0] h, best16;
        reg [15:0] x, xb;
        real fv, fbest;
        reg anynan;
        begin
            lane = 0;
            if (md == 2'b00) begin
                best8 = v[7:0];
                for (j = 1; j < 8; j = j + 1) begin
                    b8 = v[8*j +: 8];
                    if (b8 > best8) begin best8 = b8; lane = j; end
                end
                r = {{8{best8[7]}}, best8};
            end else if (md == 2'b10) begin
                anynan = 1'b0;
                for (j = 0; j < 4; j = j + 1) begin
                    x = v[16*j +: 16];
                    if (x[14:7] == 8'hFF && x[6:0] != 7'd0) anynan = 1'b1;
                end
                if (anynan) begin
                    r = 16'h7FC0; lane = -1;
                end else begin
                    xb = v[15:0]; fbest = bf2real(xb);
                    for (j = 1; j < 4; j = j + 1) begin
                        x = v[16*j +: 16]; fv = bf2real(x);
                        if (fv > fbest || (fv == fbest && xb[15] && !x[15])) begin
                            fbest = fv; xb = x; lane = j;
                        end
                    end
                    r = xb;
                end
            end else begin   // INT16, and undefined mode 11 behaves as INT16
                best16 = v[15:0];
                for (j = 1; j < 4; j = j + 1) begin
                    h = v[16*j +: 16];
                    if (h > best16) begin best16 = h; lane = j; end
                end
                r = best16;
            end
        end
    endtask

    // ---------------- stimulus helpers ----------------
    function automatic [7:0] corner8(input integer s);
        case (s % 6)
            0: corner8 = 8'h00; 1: corner8 = 8'h01; 2: corner8 = 8'h7F;
            3: corner8 = 8'h80; 4: corner8 = 8'h81; default: corner8 = 8'hFF;
        endcase
    endfunction

    function automatic [15:0] corner16(input integer s);
        case (s % 20)
            0: corner16 = 16'h0000;  1: corner16 = 16'h8000;  2: corner16 = 16'h0001;  3: corner16 = 16'h8001;
            4: corner16 = 16'h007F;  5: corner16 = 16'h0080;  6: corner16 = 16'h3F80;  7: corner16 = 16'hBF80;
            8: corner16 = 16'h7F7F;  9: corner16 = 16'hFF7F; 10: corner16 = 16'h7F80; 11: corner16 = 16'hFF80;
           12: corner16 = 16'h7FC0; 13: corner16 = 16'hFFC0; 14: corner16 = 16'h00FF; 15: corner16 = 16'h0100;
           16: corner16 = 16'h7FFF; 17: corner16 = 16'hFFFF; 18: corner16 = 16'h80FF; default: corner16 = 16'hBFC0;
        endcase
    endfunction

    function automatic [63:0] gen_vec(input [1:0] md);
        integer j;
        reg [63:0] v;
        begin
            v = {$random, $random};
            if (md == 2'b00) begin
                for (j = 0; j < 8; j = j + 1)
                    if (({$random} % 4) == 0) v[8*j +: 8] = corner8({$random} % 6);
            end else begin
                for (j = 0; j < 4; j = j + 1)
                    if (({$random} % 4) == 0) v[16*j +: 16] = corner16({$random} % 20);
            end
            gen_vec = v;
        end
    endfunction

    task automatic bf_class(input [15:0] x);
        integer c;
        begin
            if (x[14:7] == 8'h00)      c = (x[6:0] == 0) ? 0 : 1;
            else if (x[14:7] == 8'hFF) c = (x[6:0] == 0) ? 3 : 4;
            else                       c = 2;
            cov_bf[c*2 + x[15]] = cov_bf[c*2 + x[15]] + 1;
        end
    endtask

    // Drive one vector at the falling edge (no race with the DUT's rising-edge flops)
    task automatic drive(input [1:0] md, input [63:0] v, input [15:0] e);
        begin
            @(negedge clk);
            in_valid = 1'b1; mode = md; in_vec = v; cur_exp = e;
        end
    endtask

    task automatic idle(input integer n);
        integer j;
        begin
            for (j = 0; j < n; j = j + 1) begin
                @(negedge clk);
                in_valid = 1'b0; in_vec = {$random, $random}; mode = $random;   // junk while idle
            end
        end
    endtask

    // ---------------- monitor / scoreboard ----------------
    // Sampled at the rising edge: values read here are the ones held during the previous cycle.
    always @(posedge clk) begin
        cycle = cycle + 1;
        if (rst_n && in_valid) begin
            if (((wr + 1) % QSZ) == rd) begin
                $display("ERROR: scoreboard overflow"); errors = errors + 1;
            end
            exp_q[wr] = cur_exp; mode_q[wr] = mode; in_q[wr] = in_vec; t_q[wr] = cycle;
            wr = (wr + 1) % QSZ;
            ref_model(mode, in_vec, m_ref, m_lane);
            cov_mode[mode] = cov_mode[mode] + 1;
            if (mode != 2'b11) begin
                if (m_lane >= 0) cov_lane[mode*8 + m_lane] = cov_lane[mode*8 + m_lane] + 1;
                else             cov_nan_out = cov_nan_out + 1;
            end
            if (mode == 2'b10)
                for (k = 0; k < 4; k = k + 1) bf_class(in_vec[16*k +: 16]);
        end
        if (rst_n && out_valid) begin
            if (wr == rd) begin
                $display("ERROR @%0d: out_valid with nothing expected", cycle); errors = errors + 1;
            end else begin
                checked = checked + 1;
                if ((^result) === 1'bx) begin
                    $display("ERROR @%0d: X on result", cycle); errors = errors + 1;
                end else if (result !== exp_q[rd]) begin
                    errors = errors + 1;
                    if (errors <= 20)
                        $display("ERROR @%0d: mode=%0d in=%016h expected=%04h got=%04h",
                                 cycle, mode_q[rd], in_q[rd], exp_q[rd], result);
                end
                if (cycle - t_q[rd] != LAT) begin
                    errors = errors + 1;
                    if (errors <= 20)
                        $display("ERROR @%0d: latency %0d, expected %0d", cycle, cycle - t_q[rd], LAT);
                end
                rd = (rd + 1) % QSZ;
            end
        end
    end

    // ---------------- main sequence ----------------
    initial begin
        for (i = 0; i < 24; i = i + 1) cov_lane[i] = 0;
        for (i = 0; i < 10; i = i + 1) cov_bf[i] = 0;
        for (i = 0; i < 4;  i = i + 1) cov_mode[i] = 0;

        if (!$value$plusargs("VECTORS=%s", vecfile)) vecfile = "tb/vectors.hex";
        if (!$value$plusargs("NRAND=%d", nrand)) nrand = 100000;
        if ($test$plusargs("VCD")) begin
            $dumpfile("build/wave.vcd");
            $dumpvars(0, tb_vec_max_alu);
        end

        $readmemh(vecfile, mem);
        nvec = 0;
        while (nvec < MAXV && (^mem[nvec]) !== 1'bx) nvec = nvec + 1;
        $display("PIPE=%0d  latency=%0d  golden vectors=%0d  random vectors=%0d", PIPE, LAT, nvec, nrand);
        if (nvec == 0) begin
            $display("ERROR: no vectors loaded from %0s", vecfile); errors = errors + 1;
        end

        // Reset
        idle(4);
        @(negedge clk) rst_n = 1'b1;
        idle(2);

        // Phase 1: golden vectors. First 2000 back-to-back (throughput), then random gaps.
        for (i = 0; i < nvec; i = i + 1) begin
            ref_model(mem[i][81:80], mem[i][79:16], r_ref, lane_w);
            if (r_ref !== mem[i][15:0]) begin
                ref_mismatch = ref_mismatch + 1;
                if (ref_mismatch <= 10)
                    $display("REF MISMATCH: mode=%0d in=%016h golden=%04h sv_ref=%04h",
                             mem[i][81:80], mem[i][79:16], mem[i][15:0], r_ref);
            end
            if (i > 2000 && ({$random} % 8) == 0) idle(1 + {$random} % 3);
            drive(mem[i][81:80], mem[i][79:16], mem[i][15:0]);
            if (i == 2000) begin
                if ($test$plusargs("VCD")) $dumpoff;
            end
        end

        // Phase 2: random vectors, mode changes every cycle, reference = SV model
        for (i = 0; i < nrand; i = i + 1) begin
            if (({$random} % 10) == 0) idle(1);
            begin : gen
                reg [1:0]  md;
                reg [63:0] v;
                md = {$random} % 3;
                v  = gen_vec(md);
                ref_model(md, v, r_ref, lane_w);
                drive(md, v, r_ref);
            end
        end

        // Drain
        idle(LAT + 4);
        if (wr != rd) begin
            $display("ERROR: %0d results never came out", (wr - rd + QSZ) % QSZ); errors = errors + 1;
        end

        // Phase 3: mid-stream reset. Outputs must stop and stay quiet.
        for (i = 0; i < 3; i = i + 1) begin : pre
            reg [63:0] v;
            v = gen_vec(2'b01);
            ref_model(2'b01, v, r_ref, lane_w);
            drive(2'b01, v, r_ref);
        end
        @(negedge clk) begin rst_n = 1'b0; in_valid = 1'b0; end
        wr = 0; rd = 0;
        repeat (2) @(posedge clk) if (out_valid !== 1'b0) begin
            $display("ERROR: out_valid high during reset"); errors = errors + 1;
        end
        @(negedge clk) rst_n = 1'b1;
        repeat (LAT + 3) @(posedge clk) if (out_valid !== 1'b0) begin
            $display("ERROR: out_valid high after reset with no input"); errors = errors + 1;
        end
        // ...and the pipe works again afterwards
        for (i = 0; i < 50; i = i + 1) begin : post
            reg [63:0] v;
            v = gen_vec(2'b10);
            ref_model(2'b10, v, r_ref, lane_w);
            drive(2'b10, v, r_ref);
        end
        idle(LAT + 4);
        if (wr != rd) begin
            $display("ERROR: results lost after reset"); errors = errors + 1;
        end

        // ---------------- summary ----------------
        $display("---------------- coverage ----------------");
        $display("vectors per mode: INT8=%0d INT16=%0d BF16=%0d mode11=%0d",
                 cov_mode[0], cov_mode[1], cov_mode[2], cov_mode[3]);
        $display("INT8  winning lane 0..7: %0d %0d %0d %0d %0d %0d %0d %0d",
                 cov_lane[0], cov_lane[1], cov_lane[2], cov_lane[3], cov_lane[4], cov_lane[5], cov_lane[6], cov_lane[7]);
        $display("INT16 winning lane 0..3: %0d %0d %0d %0d", cov_lane[8], cov_lane[9], cov_lane[10], cov_lane[11]);
        $display("BF16  winning lane 0..3: %0d %0d %0d %0d   NaN results: %0d",
                 cov_lane[16], cov_lane[17], cov_lane[18], cov_lane[19], cov_nan_out);
        $display("BF16 input classes (+/-): zero %0d/%0d  subnormal %0d/%0d  normal %0d/%0d  inf %0d/%0d  nan %0d/%0d",
                 cov_bf[0], cov_bf[1], cov_bf[2], cov_bf[3], cov_bf[4], cov_bf[5], cov_bf[6], cov_bf[7], cov_bf[8], cov_bf[9]);
        for (i = 0; i < 8; i = i + 1)  if (cov_lane[i] == 0)      begin $display("COVERAGE HOLE: INT8 lane %0d", i);  errors = errors + 1; end
        for (i = 8; i < 12; i = i + 1) if (cov_lane[i] == 0)      begin $display("COVERAGE HOLE: INT16 lane %0d", i-8); errors = errors + 1; end
        for (i = 16; i < 20; i = i + 1) if (cov_lane[i] == 0)     begin $display("COVERAGE HOLE: BF16 lane %0d", i-16); errors = errors + 1; end
        for (i = 0; i < 10; i = i + 1) if (cov_bf[i] == 0)        begin $display("COVERAGE HOLE: BF16 class bin %0d", i); errors = errors + 1; end

        $display("------------------------------------------");
        $display("checked %0d results, %0d errors, %0d golden/SV-reference mismatches", checked, errors, ref_mismatch);
        if (errors == 0 && ref_mismatch == 0 && checked > 0) $display("TEST PASSED (PIPE=%0d)", PIPE);
        else                                                 $display("TEST FAILED (PIPE=%0d)", PIPE);
        $finish;
    end
endmodule
